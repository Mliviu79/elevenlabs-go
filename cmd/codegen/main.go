package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io"
	"log"
	"maps"
	"os"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
	"text/template"
)

const (
	pkgName         = "elevenlabs"
	receiverType    = "Client"
	defaultReceiver = "getDefaultClient()"
	genFileName     = "shorthand.go"
	genFileTemplate = `// Code generated by {{.GeneratorPath}}; DO NOT EDIT.
// Run 'go generate' after adding new methods with a '{{.ReceiverType}}' pointer receiver.

package elevenlabs

import (
	"context"
	"io"
)
{{range .Functions}}
// {{.FuncIdent}} calls the {{.FuncIdent}} method on the default client.
func {{.FuncIdent}}{{.FuncParams}}{{.FuncResults}} {
	{{if .FuncResults}}return {{end}}{{.MethodReceiver}}.{{.FuncIdent}}{{.FuncArgs}}
}
{{end}}`
)

// errPackageNotFound reports that no Go file of the directory declares the wanted package.
var errPackageNotFound = errors.New("codegen: package not found in directory")

type proxyFuncFile struct {
	GeneratorPath string
	ReceiverType  string
	Functions     []proxyFunc
}

type proxyFunc struct {
	FuncIdent, FuncParams, FuncArgs, FuncResults, MethodReceiver string
}

func main() {
	b := bytes.Buffer{}
	pkgFiles, err := parsePackage(pkgName, ".", []string{genFileName})
	if err != nil {
		log.Fatal(err)
	}
	n, err := generate(&b, pkgFiles)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(genFileName, b.Bytes(), 0644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("Wrote %d functions to %s\n", n, genFileName)
}

func generate(w io.Writer, pkgFiles map[string]*ast.File) (int, error) {
	var total int
	g, err := getCurrentRelPath()
	if err != nil {
		return 0, err
	}
	sFile := proxyFuncFile{
		GeneratorPath: g,
		ReceiverType:  receiverType,
	}
	// Files are walked in name order, so the output does not depend on map iteration order.
	for _, fileName := range slices.Sorted(maps.Keys(pkgFiles)) {
		methods := ptrRcvMethods(pkgFiles[fileName], receiverType)
		for _, m := range methods {
			sFile.Functions = append(sFile.Functions, proxyFunc{
				FuncIdent:      m.Name.Name,
				FuncParams:     genTypedParams(m.Type.Params),
				FuncArgs:       genFuncArgs(m.Type.Params),
				FuncResults:    genFuncReturnTypes(m.Type.Results),
				MethodReceiver: defaultReceiver,
			})
		}
		total += len(methods)
	}
	t := template.Must(template.New("").Parse(genFileTemplate))
	if err := t.Execute(w, sFile); err != nil {
		return 0, fmt.Errorf("render proxies: %w", err)
	}

	return total, nil
}

// parsePackage parses the Go files of the directory at path, in name order, and returns those
// whose package clause is pkgName, keyed by file name. A file named in excludeFiles is not read.
// It returns an error wrapping errPackageNotFound when no file declares pkgName.
func parsePackage(pkgName string, path string, excludeFiles []string) (map[string]*ast.File, error) {
	entries, err := os.ReadDir(path) // sorted by file name
	if err != nil {
		return nil, fmt.Errorf("list source files: %w", err)
	}
	fset := token.NewFileSet()
	pkgFiles := make(map[string]*ast.File)
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || slices.Contains(excludeFiles, name) {
			continue
		}
		fileName := filepath.Join(path, name)
		file, err := parser.ParseFile(fset, fileName, nil, 0)
		if err != nil {
			return nil, fmt.Errorf("parse source file: %w", err)
		}
		if file.Name.Name == pkgName {
			pkgFiles[fileName] = file
		}
	}
	if len(pkgFiles) == 0 {
		return nil, fmt.Errorf("%w: %q", errPackageNotFound, pkgName)
	}
	return pkgFiles, nil
}

func ptrRcvMethods(f *ast.File, receiverTypeStr string) []*ast.FuncDecl {
	methodDecls := []*ast.FuncDecl{}
	for _, decl := range f.Decls {
		if funcDecl, ok := decl.(*ast.FuncDecl); ok &&
			funcDecl.Name.IsExported() &&
			funcDecl.Recv != nil && len(funcDecl.Recv.List) > 0 { //If declaration is a exported function that has a receiver (i.e. method)
			if ptrRecvExpr, ok := funcDecl.Recv.List[0].Type.(*ast.StarExpr); ok &&
				fmt.Sprint(ptrRecvExpr.X) == receiverTypeStr {
				methodDecls = append(methodDecls, funcDecl)
			}
		}
	}
	return methodDecls
}

func genTypedParams(fl *ast.FieldList) string {
	if fl.List == nil {
		return "()"
	}
	params := make([]string, len(fl.List))
	for i, f := range fl.List {
		names := make([]string, len(f.Names))
		for j, fn := range f.Names {
			names[j] = fn.Name
		}
		paramNames := strings.Join(names, ", ")
		if paramNames != "" {
			paramNames += " "
		}
		params[i] = paramNames + exprToString(f.Type)
	}
	return fmt.Sprintf("(%s)", strings.Join(params, ", "))
}

func genFuncArgs(fl *ast.FieldList) string {
	if fl.List == nil {
		return "()"
	}
	args := make([]string, len(fl.List))
	for i, p := range fl.List {
		names := make([]string, len(p.Names))
		for j, pName := range p.Names {
			names[j] = pName.Name
		}
		paramNames := strings.Join(names, ", ")
		switch p.Type.(type) {
		case *ast.Ellipsis:
			args[i] = fmt.Sprintf("%s...", paramNames)
		default:
			args[i] = paramNames
		}
	}
	return fmt.Sprintf("(%s)", strings.Join(args, ", "))
}

func genFuncReturnTypes(fl *ast.FieldList) string {
	if fl == nil || fl.List == nil {
		return ""
	}
	ret := make([]string, len(fl.List))
	for i, f := range fl.List {
		ret[i] = exprToString(f.Type)
	}
	if len(ret) == 1 {
		return " " + ret[0]
	}
	return fmt.Sprintf(" (%s)", strings.Join(ret, ", "))
}

func exprToString(expr ast.Expr) string {
	switch fieldType := expr.(type) {
	case *ast.ArrayType:
		return fmt.Sprintf("[]%s", exprToString(fieldType.Elt))
	case *ast.Ellipsis:
		return fmt.Sprintf("...%s", exprToString(fieldType.Elt))
	case *ast.StarExpr:
		return fmt.Sprintf("*%s", exprToString(fieldType.X))
	case *ast.FuncType:
		return fmt.Sprintf("func%s%s", genTypedParams(fieldType.Params), genFuncReturnTypes(fieldType.Results))
	case *ast.SelectorExpr:
		return fmt.Sprintf("%s.%s", fieldType.X, fieldType.Sel)
	}
	return fmt.Sprintf("%s", expr)
}

func getCurrentRelPath() (string, error) {
	var path string
	_, filename, _, ok := runtime.Caller(0)
	if ok {
		currentDir, err := os.Getwd()
		if err != nil {
			return "", fmt.Errorf("find working directory: %w", err)
		}
		path, err = filepath.Rel(currentDir, filename)
		if err != nil {
			return "", fmt.Errorf("make generator path relative: %w", err)
		}
	}
	return path, nil
}
